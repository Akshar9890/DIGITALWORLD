/**
 * Helper to get cities for a given state name (case-insensitive fuzzy match).
 */
export function getCitiesForState(stateName?: string): string[] {
  if (!stateName) return [];
  const found = INDIAN_STATES.find(
    (s) => s.state.toLowerCase().trim() === stateName.toLowerCase().trim()
  );
  return found ? found.cities : ["Other"];
}

/**
 * Helper to get GST code from state name.
 */
export function getGstCodeForState(stateName?: string): string | undefined {
  if (!stateName) return undefined;
  const found = INDIAN_STATES.find(
    (s) => s.state.toLowerCase().trim() === stateName.toLowerCase().trim()
  );
  return found ? found.gstCode : undefined;
}
